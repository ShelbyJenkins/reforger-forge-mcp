import { createHash } from "node:crypto";
import { lstatSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "..");
const bundles = [
  {
    addonRoot: join(repositoryRoot, "observer", "addon"),
    manifestName: ".reforger-forge-observer-source.json",
  },
  {
    addonRoot: join(repositoryRoot, "observer", "workbench-addon"),
    manifestName: ".reforger-forge-workbench-helper-source.json",
    role: "workbench-helper",
    generate(previous, addonRoot) {
      for (const [field, pattern] of [
        ["addonId", /^[A-Za-z0-9_]+$/],
        ["addonGuid", /^[A-F0-9]{16}$/],
        ["addonVersion", /^\d+\.\d+\.\d+$/],
        ["protocolVersion", /^\d+\.\d+$/],
      ]) {
        if (typeof previous[field] !== "string" || !pattern.test(previous[field])) {
          throw new Error(`Workbench helper manifest has an invalid ${field}`);
        }
      }
      const buildPath = join(
        addonRoot,
        "Scripts",
        "WorkbenchGame",
        "EnfusionMCP",
        "RFWB_HelperBuild.c"
      );
      const identityPaths = [];
      visit(
        addonRoot,
        ".reforger-forge-workbench-helper-source.json",
        addonRoot,
        identityPaths
      );
      const identityFiles = identityPaths
        .filter((path) => path !== "Scripts/WorkbenchGame/EnfusionMCP/RFWB_HelperBuild.c")
        .sort((left, right) => left.localeCompare(right))
        .map((path) => ({
          path,
          sha256: sha256(readFileSync(join(addonRoot, ...path.split("/")))),
        }));
      const buildIdentity = aggregateDigest(identityFiles);
      const source = [
        "// Generated by scripts/update-observer-source-manifest.mjs. Do not hand-edit.",
        "class RFWB_HelperBuild",
        "{",
        "\t// Content identity of every helper payload except this generated file.",
        "\t// Any handler or project change therefore invalidates stale compiled code.",
        `\tstatic const string ADDON_ID = \"${previous.addonId}\";`,
        `\tstatic const string ADDON_GUID = \"${previous.addonGuid}\";`,
        `\tstatic const string ADDON_VERSION = \"${previous.addonVersion}\";`,
        `\tstatic const string PROTOCOL_VERSION = \"${previous.protocolVersion}\";`,
        `\tstatic const string IDENTITY = \"${buildIdentity}\";`,
        "}",
        "",
      ].join("\n");
      writeFileSync(buildPath, source, "utf8");
      const helperSourcePath = join(repositoryRoot, "src", "workbench", "helper-addon.ts");
      const helperSource = readFileSync(helperSourcePath, "utf8");
      const identityPattern = /(export const WORKBENCH_HELPER_BUILD_IDENTITY\s*=\s*)"[a-f0-9]{64}"(\s+as const;)/;
      if (!identityPattern.test(helperSource)) {
        throw new Error("Could not locate WORKBENCH_HELPER_BUILD_IDENTITY in helper-addon.ts");
      }
      const updatedHelperSource = helperSource.replace(
        identityPattern,
        `$1"${buildIdentity}"$2`
      );
      if (updatedHelperSource !== helperSource) {
        writeFileSync(helperSourcePath, updatedHelperSource, "utf8");
      }
      return buildIdentity;
    },
  },
];

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function aggregateDigest(files) {
  const aggregate = createHash("sha256");
  for (const file of files) {
    aggregate.update(file.path, "utf8");
    aggregate.update("\0", "utf8");
    aggregate.update(file.sha256, "ascii");
    aggregate.update("\n", "utf8");
  }
  return aggregate.digest("hex");
}

function visit(addonRoot, manifestName, directory, files) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const absolutePath = join(directory, entry.name);
    const stat = lstatSync(absolutePath);
    if (stat.isSymbolicLink()) {
      throw new Error(`Observer addon payload must not contain symbolic links: ${absolutePath}`);
    }
    if (entry.isDirectory()) {
      visit(addonRoot, manifestName, absolutePath, files);
      continue;
    }
    if (!entry.isFile()) {
      throw new Error(`Observer addon payload contains an unsupported filesystem entry: ${absolutePath}`);
    }
    const relativePath = relative(addonRoot, absolutePath).split(sep).join("/");
    // Workbench writes this binary cache into every opened addon. It is local
    // derived state, not source payload, and must never affect bundle identity.
    if (relativePath !== manifestName && entry.name !== "resourceDatabase.rdb") files.push(relativePath);
  }
}

for (const bundle of bundles) {
  const manifestPath = join(bundle.addonRoot, bundle.manifestName);
  const previous = JSON.parse(readFileSync(manifestPath, "utf8"));
  if (bundle.role !== undefined && previous.role !== bundle.role) {
    throw new Error(`${relative(repositoryRoot, manifestPath)} must declare role ${bundle.role}`);
  }
  const buildIdentity = bundle.generate?.(previous, bundle.addonRoot) ?? previous.buildIdentity;
  const paths = [];
  visit(bundle.addonRoot, bundle.manifestName, bundle.addonRoot, paths);
  paths.sort((left, right) => left.localeCompare(right));

  const files = paths.map((path) => ({
    path,
    sha256: sha256(readFileSync(join(bundle.addonRoot, ...path.split("/")))),
  }));

  const manifest = {
    manifestVersion: previous.manifestVersion,
    ...(bundle.role === undefined ? {} : { role: bundle.role }),
    addonVersion: previous.addonVersion,
    protocolVersion: previous.protocolVersion,
    addonId: previous.addonId,
    addonGuid: previous.addonGuid,
    buildIdentity,
    bundleDigest: aggregateDigest(files),
    files,
  };

  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
  process.stdout.write(
    `Updated ${relative(repositoryRoot, manifestPath)} (${files.length} files, ${manifest.bundleDigest})\n`
  );
}
